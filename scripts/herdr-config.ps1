# Render the Herdr configuration on Windows from this repo's template, the
# action registry and the user's own additions, then validate and install it.
# The PowerShell twin of herdr-config.sh.
#
#   herdr-config.ps1            render, validate, install, reload a running server
#   herdr-config.ps1 -Print     write the rendered config to stdout
#   herdr-config.ps1 -Check     render and validate only
#
# Popups are Bash scripts. They run through Git Bash when it is installed
# (with Git for Windows or Scoop's git), otherwise through WSL with this repo
# installed inside it; without either, the popup bindings are left out and
# the native Herdr keys still apply.
param([switch]$Print, [switch]$Check, [switch]$PrintPlugin)
$ErrorActionPreference = 'Stop'
$Root = Split-Path $PSScriptRoot
$Template = Join-Path $Root 'herdr\config.toml'
$Registry = Join-Path $Root 'actions.tsv'
$UserDir = if ($env:TMUX_THEME_DIR) { $env:TMUX_THEME_DIR } else { Join-Path $env:USERPROFILE '.config\tmux-user' }
$UserToml = Join-Path $UserDir 'herdr.toml'
$OptionsFile = Join-Path $UserDir 'options.env'
$ConfigHome = if ($env:APPDATA) { Join-Path $env:APPDATA 'herdr' } else { Join-Path $HOME '.config/herdr' }
$Target = if ($env:HERDR_CONFIG_PATH) { $env:HERDR_CONFIG_PATH } else { Join-Path $ConfigHome 'config.toml' }
$Mark = '# Generated by irlm/tmux'
$PluginId = 'irlm.workbench'
$PluginDir = Join-Path $UserDir 'herdr-plugin'

function Get-Option($name, $default) {
    if (Test-Path $OptionsFile) {
        foreach ($line in Get-Content $OptionsFile) {
            if ($line -match "^$([regex]::Escape($name))=(.*)$") { return $Matches[1].Trim() }
        }
    }
    return $default
}

function Set-Option($name, $value) {
    $lines = @()
    if (Test-Path $OptionsFile) { $lines = @(Get-Content $OptionsFile | Where-Object { $_ -notmatch "^$([regex]::Escape($name))=" }) }
    if ($value) { $lines += "$name=$value" }
    New-Item -ItemType Directory -Path $UserDir -Force | Out-Null
    Set-Content -Path $OptionsFile -Value $lines
}

function TomlString($text) { '"' + ($text -replace '\\', '\\' -replace '"', '\"') + '"' }

# "<width>", "<height>" as TOML values: the row's own WIDTHxHEIGHT or the shared size.
function PopupDimensions($shared, $own) {
    if ($own -match '^(\d+%?)x(\d+%?)$') { $width = $Matches[1]; $height = $Matches[2] } else { $width = $shared; $height = $shared }
    return @(($(if ($width -match '%') { "`"$width`"" } else { $width })), ($(if ($height -match '%') { "`"$height`"" } else { $height })))
}

# tmux key names in actions.tsv -> Herdr binding syntax under the prefix.
function HerdrKey($key) {
    if ($key -match '^C-(.)$') { return "prefix+ctrl+$($Matches[1])" }
    if ($key -cmatch '^[A-Z]$') { return "prefix+shift+$($key.ToLower())" }
    switch ($key) { '-' { return 'prefix+minus' } 'Space' { return 'prefix+space' } }
    return "prefix+$key"
}

# Where the Bash popups run: Git Bash, else WSL, else nowhere.
function Find-Bash {
    # HERDR_BASH names the bash to use (a Git Bash path; also how the tests
    # render the Windows popups on another system).
    if ($env:HERDR_BASH) { return @{ kind = 'gitbash'; path = $env:HERDR_BASH } }
    $candidates = @()
    $cmd = Get-Command bash.exe -ErrorAction SilentlyContinue
    if ($cmd) { $candidates += $cmd.Source }
    $candidates += @("$env:ProgramFiles\Git\bin\bash.exe", "$env:USERPROFILE\scoop\apps\git\current\bin\bash.exe", "$env:LOCALAPPDATA\Programs\Git\bin\bash.exe")
    foreach ($candidate in $candidates) {
        if ($candidate -and (Test-Path $candidate) -and $candidate -notmatch 'System32\\bash\.exe$') { return @{ kind = 'gitbash'; path = $candidate } }
    }
    if (Get-Command wsl.exe -ErrorAction SilentlyContinue) { return @{ kind = 'wsl'; path = 'wsl.exe' } }
    return $null
}

# Herdr runs key commands through cmd.exe /d /c, whose quote rules break a
# command that starts with a quoted path containing spaces (the popup dies
# at once with exit 1). Short 8.3 names have no spaces and need no quotes.
function ShortPath($path) {
    try {
        $fso = New-Object -ComObject Scripting.FileSystemObject
        if (Test-Path $path -PathType Leaf) { return $fso.GetFile($path).ShortPath }
        if (Test-Path $path -PathType Container) { return $fso.GetFolder($path).ShortPath }
    } catch {}
    return $path
}

# The command string Herdr runs (cmd.exe /d /c) for a script in this repo.
function ScriptCommand($bash, $script, $arguments) {
    if (-not $bash) { return $null }
    if ($bash.kind -eq 'gitbash') {
        $path = ShortPath (Join-Path $Root "scripts\$script")
        $exe = ShortPath $bash.path
        if ($exe -match ' ' -or $path -match ' ') { return "`"$exe`" `"$path`" $arguments" }
        return "$exe $path $arguments"
    }
    # WSL: the repo installed inside the distribution at the usual place.
    return "wsl.exe -e bash -lc `"~/.config/tmux/scripts/$script $arguments`""
}

function Render-Theme {
    $native = @{
        'catppuccin' = '#cdd6f4'; 'catppuccin-latte' = '#4c4f69'; 'tokyo-night' = '#c0caf5'; 'tokyo-night-day' = '#3760bf'
        'dracula' = '#f8f8f2'; 'nord' = '#eceff4'; 'gruvbox' = '#ebdbb2'; 'gruvbox-light' = '#3c3836'; 'one-dark' = '#abb2bf'
        'one-light' = '#383a42'; 'solarized' = '#93a1a1'; 'solarized-light' = '#657b83'; 'kanagawa' = '#dcd7ba'
        'kanagawa-lotus' = '#545464'; 'rose-pine' = '#e0def4'; 'rose-pine-dawn' = '#464261'; 'vesper' = '#ffffff'; 'terminal' = $null
    }
    $themes = Get-Content (Join-Path $Root 'themes.json') -Raw | ConvertFrom-Json
    $identifier = 'nord'
    $saved = Join-Path $UserDir 'theme'
    if (Test-Path $saved) { $identifier = (Get-Content $saved -Raw).Trim() }
    if (-not $themes.PSObject.Properties[$identifier]) { $identifier = 'nord' }
    $colors = $themes.$identifier.colors
    $derived = if ($identifier -eq 'catppuccin') { 'catppuccin' } else { 'nord' }
    $recorded = Get-Option 'herdr_theme' ''
    $installed = ''
    if (Test-Path $Target) {
        $text = Get-Content $Target -Raw
        if ($text.Substring(0, [Math]::Min(400, $text.Length)).Contains($Mark) -and $text -match '(?m)^\[theme\]\s*\r?\n(?:[^\[\r\n]*\r?\n)*?name\s*=\s*"([^"]*)"') { $installed = $Matches[1] }
    }
    $chosen = $recorded
    if ($installed -and $installed -ne $derived -and $installed -ne $recorded -and $native.ContainsKey($installed)) { $chosen = $installed }
    if ($chosen -ne $recorded) { Set-Option 'herdr_theme' $chosen }
    $lines = @('[theme]')
    if ($chosen -and $native.ContainsKey($chosen)) {
        $lines += "name = `"$chosen`""
        if ($native[$chosen]) { $lines += ''; $lines += '[theme.custom]'; $lines += "overlay1 = `"$($native[$chosen])`"" }
    } else {
        $lines += "name = `"$derived`""; $lines += ''; $lines += '[theme.custom]'
        foreach ($pair in @(@('text', 'foreground'), @('subtext0', 'muted'), @('overlay1', 'foreground'), @('accent', 'accent'),
                            @('blue', 'blue'), @('teal', 'cyan'), @('green', 'green'), @('yellow', 'yellow'), @('red', 'red'), @('mauve', 'magenta'))) {
            $lines += "$($pair[0]) = `"$($colors.($pair[1]))`""
        }
    }
    return ($lines -join "`n")
}

function Render-Config {
    $bash = Find-Bash
    $size = Get-Option 'popup_size' '85%'
    if ($size -notmatch '^[0-9]+%?$') { $size = '85%' }
    $out = New-Object System.Text.StringBuilder
    [void]$out.AppendLine("$Mark on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss'). Do not edit: personal settings belong in $UserToml")
    [void]$out.AppendLine('')
    $theme = Render-Theme
    # The readings come from status_right.ps1, every ten seconds: a PowerShell
    # start costs more than the Unix script, so the interval is longer.
    $psExe = 'powershell.exe'
    if ($env:SystemRoot) { $psExe = ShortPath (Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe') }
    $statusScript = ShortPath (Join-Path $Root 'scripts\status_right.ps1')
    $statusCommand = "$psExe -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $statusScript"
    if ((Get-Option 'herdr_status_colors' 'off') -eq 'on') {
        $themes = Get-Content (Join-Path $Root 'themes.json') -Raw | ConvertFrom-Json
        $identifier = 'nord'; $saved = Join-Path $UserDir 'theme'
        if (Test-Path $saved) { $identifier = (Get-Content $saved -Raw).Trim() }
        if (-not $themes.PSObject.Properties[$identifier]) { $identifier = 'nord' }
        $colors = $themes.$identifier.colors
        $status = (@(@('net', 'magenta'), @('cpu', 'accent'), @('ram', 'yellow'), @('battery', 'green')) | ForEach-Object {
            "  { type = `"command`", command = $(TomlString "$statusCommand -Part $($_[0])"), interval_seconds = 10, timeout_seconds = 5, color = `"$($colors.($_[1]))`" },"
        }) -join "`n"
    } else {
        $status = "  { type = `"command`", command = $(TomlString $statusCommand), interval_seconds = 10, timeout_seconds = 5 },"
    }
    foreach ($line in Get-Content $Template) {
        if ($line -match '@@THEME@@') { [void]$out.AppendLine($theme); continue }
        if ($line -match '@@STATUS_ENTRIES@@') { [void]$out.AppendLine($status); continue }
        if ($line -match '^command = "bash @@SCRIPTS@@/(\S+) (\w+)"$') {
            $command = ScriptCommand $bash $Matches[1] $Matches[2]
            if (-not $command) { $command = 'rem no bash for the navigation helper' }
            [void]$out.AppendLine("command = $(TomlString $command)"); continue
        }
        [void]$out.AppendLine($line)
    }
    [void]$out.AppendLine('')
    if ($bash) {
        [void]$out.AppendLine('# ─── Popups generated from actions.tsv ───────────────────')
        foreach ($row in Import-Csv $Registry -Delimiter "`t") {
            if (-not $row.id -or $row.hosts -eq 'tmux') { continue }
            if ($row.id -in @('new-session', 'rename-session', 'rename-window')) { continue }
            [void]$out.AppendLine('')
            [void]$out.AppendLine('[[keys.command]]')
            [void]$out.AppendLine("key = $(TomlString (HerdrKey $row.key))")
            [void]$out.AppendLine('type = "popup"')
            [void]$out.AppendLine("command = $(TomlString (ScriptCommand $bash 'actions.sh' "run $($row.id)"))")
            $dims = PopupDimensions $size $row.size
            [void]$out.AppendLine("width = $($dims[0])")
            [void]$out.AppendLine("height = $($dims[1])")
            [void]$out.AppendLine("description = $(TomlString $row.label)")
        }
    } else {
        [void]$out.AppendLine('# No Git Bash or WSL found: the popups are not bound. Install Git for Windows and rerun scripts\herdr-config.ps1.')
    }
    if (Test-Path $UserToml) {
        [void]$out.AppendLine('')
        [void]$out.AppendLine("# ─── $UserToml ───")
        [void]$out.AppendLine((Get-Content $UserToml -Raw))
    }
    return $out.ToString()
}

function Render-Plugin {
    $bash = Find-Bash
    $size = Get-Option 'popup_size' '85%'
    $lines = @($Mark, "id = `"$PluginId`"", 'name = "Workbench"', 'version = "0.1.0"', 'min_herdr_version = "0.9.0"',
               'description = "The irlm/tmux popups: command palette, projects, notes, search, references, themes"',
               'platforms = ["linux", "macos", "windows"]')
    if (-not $bash -or $bash.kind -ne 'gitbash') { return ($lines -join "`n") }
    foreach ($row in Import-Csv $Registry -Delimiter "`t") {
        if (-not $row.id -or $row.hosts -eq 'tmux' -or $row.id -in @('new-session', 'rename-session', 'rename-window')) { continue }
        $script = (Join-Path $Root 'scripts\actions.sh')
        $lines += ''; $lines += '[[panes]]'; $lines += "id = `"$($row.id)`""; $lines += "title = $(TomlString $row.label)"
        $dims = PopupDimensions $size $row.size
        $lines += 'placement = "popup"'; $lines += "width = $($dims[0])"; $lines += "height = $($dims[1])"
        $lines += "command = [$(TomlString $bash.path), $(TomlString $script), `"run`", `"$($row.id)`"]"
    }
    return ($lines -join "`n")
}

if ($Print) { Write-Output (Render-Config); exit 0 }
if ($PrintPlugin) { Write-Output (Render-Plugin); exit 0 }
$herdr = Get-Command herdr -ErrorAction SilentlyContinue
if (-not $herdr) { Write-Error 'herdr is not installed (https://herdr.dev).'; exit 127 }
$staged = Join-Path ([System.IO.Path]::GetTempPath()) ("herdr-config-" + [guid]::NewGuid().ToString('N') + '.toml')
try {
    Set-Content -Path $staged -Value (Render-Config) -NoNewline
    $env:HERDR_CONFIG_PATH_SAVED = $env:HERDR_CONFIG_PATH
    $env:HERDR_CONFIG_PATH = $staged
    $report = & herdr config check 2>&1 | Out-String
    $code = $LASTEXITCODE
    $env:HERDR_CONFIG_PATH = $env:HERDR_CONFIG_PATH_SAVED
    if ($code -ne 0) { Write-Error "Rendered Herdr config was rejected:`n$report"; exit 1 }
    if ($report -match 'issues found') { Write-Output $report }
    if ($Check) { Write-Output 'Herdr config renders and validates.'; exit 0 }
    New-Item -ItemType Directory -Path (Split-Path $Target) -Force | Out-Null
    if ((Test-Path $Target) -and -not ((Get-Content $Target -First 3 | Out-String).Contains($Mark))) {
        $backup = "$Target.backup.$(Get-Date -Format 'yyyyMMdd-HHmmss')"
        Copy-Item $Target $backup
        Write-Output "Previous Herdr config saved to $backup"
    }
    Copy-Item $staged $Target -Force
    Write-Output "Herdr config written to $Target"
} finally {
    if (Test-Path $staged) { Remove-Item $staged -Force }
}
New-Item -ItemType Directory -Path $PluginDir -Force | Out-Null
Set-Content -Path (Join-Path $PluginDir 'herdr-plugin.toml') -Value (Render-Plugin)
$list = & herdr plugin list 2>&1 | Out-String
if ($list -match [regex]::Escape($PluginId)) { Write-Output "Herdr plugin $PluginId refreshed in $PluginDir" }
else {
    & herdr plugin link $PluginDir *> $null
    if ($LASTEXITCODE -eq 0) { Write-Output "Herdr plugin $PluginId linked from $PluginDir" } else { Write-Warning "Could not link the Herdr plugin; run: herdr plugin link $PluginDir" }
}
$status = & herdr status server 2>&1 | Out-String
if ($status -match 'status: running') { & herdr server reload-config *> $null; if ($LASTEXITCODE -eq 0) { Write-Output 'Running Herdr server reloaded.' } }
