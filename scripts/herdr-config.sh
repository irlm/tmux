#!/usr/bin/env bash
# Render the Herdr configuration from this repo's template, the action
# registry, and the user's own additions, then validate and install it.
#
#   herdr-config.sh            render, validate, install, reload a running server
#   herdr-config.sh --print    write the rendered config to stdout
#   herdr-config.sh --check    render and validate only
#
# Layers, in order: herdr/config.toml (template), one popup binding per row
# of actions.tsv, then ~/.config/tmux-user/herdr.toml appended verbatim for
# tables the template does not define (theme.custom, extra keys.command, ...).
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=scripts/lib.sh
source "$SCRIPT_DIR/lib.sh"
TEMPLATE="$SCRIPT_DIR/../herdr/config.toml"
REGISTRY="$SCRIPT_DIR/../actions.tsv"
USER_TOML="$TMUX_USER_DIR/herdr.toml"
HERDR_DIR="${HERDR_CONFIG_DIR:-$HOME/.config/herdr}"
TARGET="${HERDR_CONFIG_PATH:-$HERDR_DIR/config.toml}"
MARK='# Generated by irlm/workbench'   # older files say irlm/tmux

# tmux key names in actions.tsv -> Herdr binding syntax under the prefix.
herdr_key() {
    local key=$1
    case "$key" in
        C-?) printf 'prefix+ctrl+%s' "${key#C-}" ;;
        [[:upper:]]) printf 'prefix+shift+%s' "$(printf '%s' "$key" | tr '[:upper:]' '[:lower:]')" ;;
        -) printf 'prefix+minus' ;;
        Space) printf 'prefix+space' ;;
        *) printf 'prefix+%s' "$key" ;;
    esac
}

# "<width> <height>" as TOML values: the row's own WIDTHxHEIGHT (cells as
# numbers, percentages as strings) or the shared popup size for both.
popup_dimensions() {
    local shared=$1 own=$2 width height
    case "$own" in
        [0-9]*x[0-9]*) width=${own%x*}; height=${own#*x} ;;
        *) width=$shared; height=$shared ;;
    esac
    case "$width" in *%) width="\"$width\"" ;; esac
    case "$height" in *%) height="\"$height\"" ;; esac
    printf '%s %s\n' "$width" "$height"
}

toml_string() {  # escape for a basic TOML string
    local s=${1//\\/\\\\}
    printf '"%s"' "${s//\"/\\\"}"
}

# [theme]: by default the palette saved by C-a C-t. Nord and Catppuccin map
# onto Herdr's own themes; High contrast is Nord with brighter tokens; the
# palette's full text colour replaces overlay1, the token Herdr paints the
# tab bar status with, which its themes keep too dim to read.
#
# A theme picked in Herdr's own settings wins until the next C-a C-t: Herdr
# writes it into the rendered file, this notices the change, records it as
# herdr_theme in options.env, and keeps emitting it with only overlay1 raised
# to that theme's own text colour.
render_theme() {
    python3 - "$SCRIPT_DIR" "$TARGET" "$TMUX_USER_DIR/options.env" "$MARK" <<'PY'
import os, re, sys
sys.path.insert(0, sys.argv[1])
from appearance import current_theme
target, options_path, mark = sys.argv[2], sys.argv[3], sys.argv[4]
# Main text colour of each built-in Herdr theme (src/app/state.rs, v0.9.5).
NATIVE = {
    'catppuccin': '#cdd6f4', 'catppuccin-latte': '#4c4f69', 'tokyo-night': '#c0caf5',
    'tokyo-night-day': '#3760bf', 'dracula': '#f8f8f2', 'nord': '#eceff4', 'gruvbox': '#ebdbb2',
    'gruvbox-light': '#3c3836', 'one-dark': '#abb2bf', 'one-light': '#383a42', 'solarized': '#93a1a1',
    'solarized-light': '#657b83', 'kanagawa': '#dcd7ba', 'kanagawa-lotus': '#545464',
    'rose-pine': '#e0def4', 'rose-pine-dawn': '#464261', 'vesper': '#ffffff', 'terminal': None,
}
identifier, theme = current_theme()
colors = theme['colors']
derived = 'catppuccin' if identifier == 'catppuccin' else 'nord'

options = []
try:
    options = open(options_path, encoding='utf-8').read().splitlines()
except OSError:
    pass
recorded = next((line.split('=', 1)[1].strip() for line in options if line.startswith('herdr_theme=')), '')

installed = ''
try:
    with open(target, encoding='utf-8') as stream:
        text = stream.read()
    if mark in text[:400] or '# Generated by irlm/tmux' in text[:400]:
        match = re.search(r'^\[theme\]\s*\n(?:[^\[\n]*\n)*?name\s*=\s*"([^"]*)"', text, re.M)
        installed = match.group(1) if match else ''
except OSError:
    pass
chosen = recorded
if installed and installed != derived and installed != recorded and installed in NATIVE:
    chosen = installed   # picked inside Herdr since the last render: keep it
if chosen != recorded:
    kept = [line for line in options if not line.startswith('herdr_theme=')]
    if chosen:
        kept.append('herdr_theme=' + chosen)
    try:
        os.makedirs(os.path.dirname(options_path), exist_ok=True)
        with open(options_path, 'w', encoding='utf-8') as stream:
            stream.write(''.join(line + '\n' for line in kept))
    except OSError:
        pass

print('[theme]')
if chosen in NATIVE:
    print(f'name = "{chosen}"')
    if NATIVE[chosen]:
        print('')
        print('[theme.custom]')
        print(f'overlay1 = "{NATIVE[chosen]}"')
else:
    print(f'name = "{derived}"')
    print('')
    print('[theme.custom]')
    for token, role in (('text', 'foreground'), ('subtext0', 'muted'), ('overlay1', 'foreground'),
                        ('accent', 'accent'), ('blue', 'blue'), ('teal', 'cyan'), ('green', 'green'),
                        ('yellow', 'yellow'), ('red', 'red'), ('mauve', 'magenta')):
        print(f'{token} = "{colors[role]}"')
PY
}

# The tab bar readings: one entry running the whole status line, or, when
# herdr_status_colors=on and the Herdr in use accepts a color per entry, one
# entry per reading painted like the tmux status line. Each part reads the
# same five-second sample, so four entries still measure once.
render_status_entries() {
    local status=$1 part role
    if [ "$(tmux_option @herdr_status_colors off)" != on ]; then
        printf '  { type = "command", command = %s, interval_seconds = 5, timeout_seconds = 3 },' "$(toml_string "$status")"
        return
    fi
    for part in net:magenta cpu:accent ram:yellow battery:green holiday:accent; do
        role=${part#*:}; part=${part%%:*}
        printf '  { type = "command", command = %s, interval_seconds = 5, timeout_seconds = 3, color = %s },\n' \
            "$(toml_string "$status --part $part")" "$(toml_string "$(palette_color "$role")")"
    done
}

palette_color() {  # a role from the saved palette (themes.json)
    python3 - "$SCRIPT_DIR" "$1" <<'PY'
import sys
sys.path.insert(0, sys.argv[1])
from appearance import current_theme
print(current_theme()[1]['colors'][sys.argv[2]], end='')
PY
}

render() {
    local size status key id label theme entries
    size=$(tmux_option @popup_size 85%)
    case "$size" in *[!0-9%]*|'') size=85% ;; esac
    status="bash $(printf '%q' "$SCRIPT_DIR/status_right.sh") --plain 160"
    entries=$(render_status_entries "$status")
    local sort worktrees
    sort=$(tmux_option @herdr_agent_sort priority)
    case "$sort" in spaces|priority) ;; *) sort=priority ;; esac
    # shellcheck disable=SC2088  # Herdr expands the tilde itself
    worktrees=$(tmux_option @worktree_dir "~/.herdr/worktrees")
    printf '%s on %s. Do not edit: personal settings belong in %s\n\n' "$MARK" "$(date '+%F %T')" "$USER_TOML"
    theme=$(render_theme) || theme='[theme]
name = "nord"'
    # The theme block spans lines; macOS awk refuses newlines in -v values.
    WB_THEME="$theme" WB_STATUS_ENTRIES="$entries" awk -v scripts="$(printf '%q' "$SCRIPT_DIR")" \
        -v sort="$sort" -v worktrees="$(toml_string "$worktrees")" \
        '/@@THEME@@/ { print ENVIRON["WB_THEME"]; next }
         /@@STATUS_ENTRIES@@/ { print ENVIRON["WB_STATUS_ENTRIES"]; next }
         { gsub(/@@SCRIPTS@@/, scripts); gsub(/@@AGENT_SORT@@/, sort); gsub(/"@@WORKTREE_DIR@@"/, worktrees); print }' "$TEMPLATE"
    printf '\n# ─── Popups generated from actions.tsv ───────────────────\n'
    while IFS=$'\t' read -r key id label _ hosts own; do
        own=${own%$'\r'}
        [ "$key" != key ] && [ -n "$id" ] && [ "${hosts:-all}" != tmux ] || continue
        # Herdr prompts for these itself (new_workspace, rename_*).
        case "$id" in new-session|rename-session|rename-window) continue ;; esac
        read -r width height <<< "$(popup_dimensions "$size" "$own")"
        printf '\n[[keys.command]]\nkey = %s\ntype = "popup"\ncommand = %s\nwidth = %s\nheight = %s\ndescription = %s\n' \
            "$(toml_string "$(herdr_key "$key")")" \
            "$(toml_string "bash $(printf '%q' "$SCRIPT_DIR/actions.sh") run $id")" \
            "$width" "$height" "$(toml_string "$label")"
    done < "$REGISTRY"
    if [ -f "$USER_TOML" ]; then
        printf '\n# ─── %s ───\n' "$USER_TOML"
        cat "$USER_TOML"
    fi
}

# The same popups as a Herdr plugin, so they also open from plugin menus and
# `herdr plugin pane open`. Rendered outside the checkout because the linked
# directory is user state; commands point back at this repo's scripts.
PLUGIN_ID="irlm.workbench"
PLUGIN_DIR="$TMUX_USER_DIR/herdr-plugin"
render_plugin() {
    local size key id label hosts
    size=$(tmux_option @popup_size 85%)
    case "$size" in *[!0-9%]*|'') size=85% ;; esac
    printf '%s\n' "$MARK" \
        "id = \"$PLUGIN_ID\"" 'name = "Workbench"' 'version = "0.1.0"' 'min_herdr_version = "0.9.0"' \
        'description = "The irlm/workbench popups: command palette, projects, notes, search, references, themes"' \
        'platforms = ["linux", "macos"]'
    # Every agent state change: journal it and report the size of the
    # uncommitted work as the workspace's $changes sidebar token.
    printf '\n[[events]]\non = "pane.agent_status_changed"\ncommand = ["bash", %s]\n' "$(toml_string "$SCRIPT_DIR/agent-events.sh")"
    for id in palette projects notes help; do
        label=$(awk -F '\t' -v id="$id" '$2 == id {print $3}' "$REGISTRY")
        printf '\n[[actions]]\nid = "%s"\ntitle = %s\ncontexts = ["workspace"]\ncommand = [%s, "plugin", "pane", "open", "--plugin", "%s", "--entrypoint", "%s", "--placement", "popup", "--width", "%s", "--height", "%s"]\n' \
            "$id" "$(toml_string "$label")" "$(toml_string "${HERDR_BIN_PATH:-herdr}")" "$PLUGIN_ID" "$id" "$size" "$size"
    done
    while IFS=$'\t' read -r key id label _ hosts own; do
        own=${own%$'\r'}
        [ "$key" != key ] && [ -n "$id" ] && [ "${hosts:-all}" != tmux ] || continue
        case "$id" in new-session|rename-session|rename-window) continue ;; esac
        read -r width height <<< "$(popup_dimensions "$size" "$own")"
        printf '\n[[panes]]\nid = "%s"\ntitle = %s\nplacement = "popup"\nwidth = %s\nheight = %s\ncommand = ["bash", %s, "run", "%s"]\n' \
            "$id" "$(toml_string "$label")" "$width" "$height" "$(toml_string "$SCRIPT_DIR/actions.sh")" "$id"
    done < "$REGISTRY"
}

install_plugin() {
    local linked
    mkdir -p "$PLUGIN_DIR" || return 1
    render_plugin > "$PLUGIN_DIR/herdr-plugin.toml" || return 1
    # Plugin links are global to the user: find where this id points now.
    linked=$(herdr plugin list --json 2>/dev/null | python3 -c '
import json, sys
try:
    plugins = json.load(sys.stdin)["result"]["plugins"]
except Exception:
    sys.exit(0)
for plugin in plugins:
    if plugin.get("plugin_id") == sys.argv[1]:
        print(plugin.get("plugin_root", ""), end="")' "$PLUGIN_ID")
    if [ "$linked" = "$PLUGIN_DIR" ]; then
        printf 'Herdr plugin %s refreshed in %s\n' "$PLUGIN_ID" "$PLUGIN_DIR"
        return 0
    fi
    if [ -n "$linked" ]; then
        # Linked from somewhere else (a moved checkout, a stale directory):
        # point it here, or events and panes silently stop working.
        herdr plugin unlink "$PLUGIN_ID" >/dev/null 2>&1 || true
        printf 'Herdr plugin %s was linked from %s\n' "$PLUGIN_ID" "$linked"
    fi
    if herdr plugin link "$PLUGIN_DIR" >/dev/null 2>&1; then
        printf 'Herdr plugin %s linked from %s\n' "$PLUGIN_ID" "$PLUGIN_DIR"
    else
        printf 'Could not link the Herdr plugin; run: herdr plugin link %s\n' "$PLUGIN_DIR" >&2
        return 1
    fi
}

mode=${1:-install}
case "$mode" in
    --print) render; exit 0 ;;
    --print-plugin) render_plugin; exit 0 ;;
    --check|install) ;;
    *) printf 'Usage: herdr-config.sh [--print | --check]\n' >&2; exit 2 ;;
esac
command -v herdr >/dev/null 2>&1 || { echo 'herdr is not installed (https://herdr.dev).' >&2; exit 127; }
if message=$(herdr_too_old); then printf '%s\n' "$message" >&2; exit 1; fi
staged=$(mktemp "${TMPDIR:-/tmp}/herdr-config.XXXXXX") || exit 1
trap 'rm -f -- "$staged"' EXIT
render > "$staged"
if ! report=$(HERDR_CONFIG_PATH="$staged" herdr config check 2>&1); then
    printf 'Rendered Herdr config was rejected:\n%s\n' "$report" >&2
    exit 1
fi
case "$report" in *"issues found"*) printf '%s\n' "$report" ;; esac
[ "$mode" != --check ] || { echo 'Herdr config renders and validates.'; exit 0; }
mkdir -p "$(dirname "$TARGET")" || exit 1
if [ -f "$TARGET" ] && ! head -3 "$TARGET" | grep -qE 'Generated by irlm/(workbench|tmux)'; then
    backup="$TARGET.backup.$(date +%Y%m%d-%H%M%S)"
    cp -p -- "$TARGET" "$backup" && printf 'Previous Herdr config saved to %s\n' "$backup"
fi
cp -- "$staged" "$TARGET" || exit 1
chmod 600 "$TARGET"
printf 'Herdr config written to %s\n' "$TARGET"
install_plugin || true
if herdr status server 2>/dev/null | grep -q 'status: running'; then
    herdr server reload-config >/dev/null 2>&1 && echo 'Running Herdr server reloaded.'
    # Keys and theme are read by the client: an attached Herdr keeps the old
    # ones (and the old prefix) until it reloads or restarts.
    echo 'An attached Herdr keeps its previous keys until you reload it (its reload key, C-a r here; ctrl+b shift+r on a stock config) or detach and start herdr again.'
fi
